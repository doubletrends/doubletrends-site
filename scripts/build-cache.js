'use strict';
/**
 * Browser caching, so the house faces are on hand at first paint.
 *
 * Without this every file is served `max-age=0, must-revalidate`: on each
 * page change the browser must ask the server about every font before using
 * it, and since the faces are `font-display: swap` it paints the text in a
 * fallback face meanwhile, then swaps (the flash of unstyled text between
 * pages). So:
 *
 *   fonts       cached a year, immutable. A changed font must get a new
 *               file name, or returning visitors keep the old one.
 *   site.css    cached a year, immutable; every page links it as
 *               site.css?v=<hash of its content>, so a deploy that changes
 *               the CSS changes the URL.
 *   images      a day, then served from cache while it revalidates.
 *   pages, js   unchanged: revalidated on every load, so a deploy shows at once.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const YEAR = 'public, max-age=31536000, immutable';
const DAY = 'public, max-age=86400, stale-while-revalidate=604800';

function writeHeaders(dist) {
  const rule = (pattern, value) => `${pattern}\n  Cache-Control: ${value}`;
  const file = [
    '# Generated by scripts/build-cache.js; see the note there.',
    rule('/public/fonts/*', YEAR),
    rule('/public/styles/*', YEAR),
    rule('/public/img/*', DAY),
    rule('/public/brand/*', DAY),
    '',
  ].join('\n\n');
  fs.writeFileSync(path.join(dist, '_headers'), file);
}

function htmlFiles(dir) {
  return fs.readdirSync(dir, { recursive: true })
    .filter((f) => f.endsWith('.html'))
    .map((f) => path.join(dir, f));
}

/** Adds ?v=<content hash> to every page's site.css link. Returns pages stamped. */
function stampStylesheet(dist) {
  const css = fs.readFileSync(path.join(dist, 'public', 'styles', 'site.css'));
  const v = crypto.createHash('sha256').update(css).digest('hex').slice(0, 10);
  let stamped = 0;
  for (const file of htmlFiles(dist)) {
    const html = fs.readFileSync(file, 'utf8');
    const out = html.replace(/(href="[^"?]*public\/styles\/site\.css)"/g, `$1?v=${v}"`);
    if (out !== html) { fs.writeFileSync(file, out); stamped++; }
  }
  return stamped;
}

/**
 * Replaces each <img src=".../brand/logo.svg"> with the SVG itself, so the mark
 * paints with the page's first frame instead of a beat after the text (an
 * image is fetched and decoded separately). The mark has no ids, so copies
 * cannot collide. Returns the number of marks inlined.
 */
function inlineLogo(dist) {
  const svg = fs.readFileSync(path.join(dist, 'public', 'brand', 'logo.svg'), 'utf8');
  const [, attrs, inner] = svg.match(/<svg([^>]*)>([\s\S]*)<\/svg>/);
  const viewBox = attrs.match(/viewBox="[^"]*"/)[0];
  const img = /<img (class="[^"]*" )?src="[^"]*brand\/logo\.svg" alt="" width="(\d+)" height="(\d+)" \/>/g;
  let count = 0;
  for (const file of htmlFiles(dist)) {
    const html = fs.readFileSync(file, 'utf8');
    const out = html.replace(img, (_, cls = '', w, h) => {
      count++;
      return `<svg ${cls}xmlns="http://www.w3.org/2000/svg" ${viewBox} width="${w}" height="${h}" aria-hidden="true" focusable="false">${inner.trim()}</svg>`;
    });
    if (out !== html) fs.writeFileSync(file, out);
  }
  return count;
}

module.exports = { writeHeaders, stampStylesheet, inlineLogo };
